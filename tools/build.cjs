#!/usr/bin/env node
// Builds everything from src/fister-vr.js:
//   docs/index.html               the Quest setup page (GitHub Pages serves the docs/ folder)
//   dist/fister-vr.user.js        Tampermonkey / Violentmonkey userscript for PC browsers
//   dist/fister-vr.bookmarklet.txt bookmarklet with default settings
//   dist/fisterVr.js              copy for the Steam launcher patch (see steam/README.md)
// and, from qol/FisterQoL.user.template.js (FisterQoL with this layer inside):
//   dist/FisterQoL.user.js        FisterQoL for Tampermonkey (PC), with QoL > VR
//   dist/fisterqol.bookmarklet.js FisterQoL reformatted to run from a bookmarklet (readable)
//   dist/fister-vr-qol.bookmarklet.txt  "Fister VR + FisterQoL" bookmarklet with default settings
// Usage: node tools/build.cjs
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, text) => {
  fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
  fs.writeFileSync(path.join(root, p), text);
  console.log('wrote', p, '(' + Buffer.byteLength(text) + ' bytes)');
};

const source = read('src/fister-vr.js');
const version = (source.match(/@version\s+([\d.]+)/) || [])[1] || 'dev';

// Bookmarklets can't carry comments safely across lines; drop full-line comments and indentation.
// (The source has no multi-line strings, so this is safe.)
const body = source.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('//')).join('\n');
new Function(body); // syntax check

write('dist/fister-vr.user.js', source);
write('dist/fisterVr.js', source);
write('dist/fister-vr.bookmarklet.txt', 'javascript:' + encodeURIComponent(body + '\nvoid 0;'));

// ---- FisterQoL ------------------------------------------------------------------------------------------------
// The template is the Tampermonkey userscript with `const VR_SOURCE=__FISTER_VR_SOURCE__;` where this layer goes.
const qolTemplate = read('qol/FisterQoL.user.template.js');
const qolVersion = (qolTemplate.match(/@version\s+([\d.]+)/) || [])[1] || 'dev';
const vrSlot = 'const VR_SOURCE=__FISTER_VR_SOURCE__;';
if (qolTemplate.split(vrSlot).length !== 2) throw new Error('qol template: VR_SOURCE slot missing');
const withVr = (vr) => qolTemplate.replace(vrSlot, () => 'const VR_SOURCE=' + JSON.stringify(vr) + ';');
const qolUserscript = withVr(source);
new Function(qolUserscript.replace(/^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\n/, ''));
write('dist/FisterQoL.user.js', qolUserscript);

// Bookmarklet format: the userscript assumes Tampermonkey (metadata block, unsafeWindow, GM_addElement, document-start).
// A bookmarklet runs as a plain page script after the page has loaded, so swap those for page equivalents.
function qolForBookmarklet() {
  let code = withVr(body);
  const swap = (from, to) => {
    if (code.split(from).length !== 2) throw new Error('qol bookmarklet: expected exactly one match for ' + from.slice(0, 60));
    code = code.replace(from, () => to);
  };
  code = code.replace(/^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\n/, '// FisterQoL ' + qolVersion + ' (bookmarklet build) with Fister VR ' + version + '. Generated by tools/build.cjs.\n');
  swap("const window=typeof unsafeWindow!=='undefined'?unsafeWindow:globalThis;", 'const window=globalThis;');
  swap("if(typeof GM_addElement==='function')GM_addElement(parent,'script',{textContent:code});else{const el=document.createElement('script');el.textContent=code;parent.appendChild(el);el.remove();}",
    "const el=document.createElement('script');el.textContent=code;parent.appendChild(el);el.remove();");
  swap("if(typeof window.__fisterQolStageModule==='function'){const moduleSource=script.textContent;script.textContent='';window.__fisterQolStageModule(moduleSource).then(url=>{script.src=url;document.head.appendChild(script);}).catch(fail);}else if(typeof GM_addElement==='function'){GM_addElement(document.head,'script',{type:'module',id:script.id,textContent:script.textContent});}else document.head.appendChild(script);",
    'document.head.appendChild(script);');
  swap("The game started before the QoL hook. Set Tampermonkey injection to document-start and reload.",
    "The game started loading before FisterQoL. Reload fister.fun and tap the bookmark again right away, before tapping anything on the page.");
  if (/GM_addElement|unsafeWindow|Tampermonkey/.test(code)) throw new Error('qol bookmarklet: Tampermonkey-only code left');
  new Function(code);
  return code;
}
const qolBookmarkletCode = qolForBookmarklet();
write('dist/fisterqol.bookmarklet.js', qolBookmarkletCode);
const qolPayload = zlib.gzipSync(Buffer.from(qolBookmarkletCode, 'utf8'), { level: 9 }).toString('base64');
const loaderSource = read('site/qol-loader.js');
const { qolLoader } = require(path.join(root, 'site/qol-loader.js'));
const qolDefaultCode = qolLoader(qolPayload, {}, false);
new Function(qolDefaultCode);
write('dist/fister-vr-qol.bookmarklet.txt', 'javascript:' + encodeURIComponent(qolDefaultCode));

// Setup page: embed the layer as a safe JS string literal and wrap the template into a full HTML document.
const safeLiteral = (text) => JSON.stringify(text)
  .replace(/</g, '\\u003c')
  .split(String.fromCharCode(0x2028)).join('\\u2028')
  .split(String.fromCharCode(0x2029)).join('\\u2029');
const literal = safeLiteral(body);
const loaderInline = loaderSource.replace(/^if \(typeof module[^\n]*\n?/m, '').replace(/<\/script/gi, '<\\/script');
const template = read('site/page-template.html').replace('__LAYER_SOURCE__', () => literal)
  .replace('__QOL_PAYLOAD__', () => safeLiteral(qolPayload))
  .replace('__QOL_LOADER__', () => loaderInline)
  .split('__QOL_VERSION__').join(qolVersion)
  .split('__VERSION__').join(version);
const split = template.indexOf('</style>') + '</style>'.length;
const html = '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
  + '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
  + '<meta name="description" content="Unofficial WebXR mod: play fister.fun in a Quest headset from the Quest Browser.">\n'
  + template.slice(0, split) + '\n</head>\n<body>\n' + template.slice(split).trim() + '\n</body>\n</html>\n';
write('docs/index.html', html);
console.log('Fister VR', version, '+ FisterQoL', qolVersion, 'built.');
